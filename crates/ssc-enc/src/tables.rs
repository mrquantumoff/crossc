/// Parameters of one SSC codec mode (44.1/48 kHz or 96 kHz).
pub(crate) struct ModeTables {
    /// 23 band edges, in units of 8 MDCT bins.
    pub e_bands: &'static [i16; 23],
    /// Allocation vectors: [0] for bitrate <= 192000, [1] for bitrate > 192000 (11 x 22 each).
    pub alloc_vectors: [&'static [u8; 242]; 2],
    pub log_n: &'static [i16; 22],
    /// 5 x 22, row = LM + 1.
    pub cache_index: &'static [i16; 110],
    pub cache_bits: &'static [u8],
    /// Per-band cap in 1/8 bits (C = 2, LM = 3).
    pub cap: &'static [i32; 22],
}

