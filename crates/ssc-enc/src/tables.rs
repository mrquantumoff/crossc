/// U(N,K) of the PVQ codebook sizes: row `min(n, k)`, column `max(n, k)` (libopus 1.1 cwrs.c table form).
#[inline]
pub(crate) fn pvq_u(n: i32, k: i32) -> u32 {
    let (a, b) = if n < k { (n, k) } else { (k, n) };
    PVQ_U_DATA[PVQ_U_ROW[a as usize] + b as usize]
}

